#!/usr/bin/env python3
"""Publish the ordinals of core's Solidity enums, so consumers stop transcribing them.

Four repositories branch on `ILPAdapter.LPType` and `IPositionManager.PositionStatus`,
and every one of them re-declares the mapping by hand. Nothing checks those copies
against the source, and nothing can: an ABI encodes an enum parameter as `uint8` and
carries no member names at all, so a regenerate-and-diff check over ABIs regenerates
cleanly, diffs cleanly and reports green while every label is wrong. Struct component
names do survive an ABI, which is why the struct half of this problem is solvable
without this script and the enum half is not.

A hand-typed constant does not have to drift to be wrong. It only has to be typed once,
and then nothing downstream ever disagrees with it. That is not hypothetical here: the
SDK shipped `PositionStatus.Liquidated = 2` for as long as it has existed, where 2 is
`Closed` on chain, so the check matched every closed position and missed every
liquidated one.

The AST is solc's own record of what it compiled, so unlike a list of names written out
by hand in Solidity or TypeScript it cannot disagree with the enum it describes.

Usage:
    python3 script/tools/gen_enums.py            # write exports/enums.json
    python3 script/tools/gen_enums.py --check    # exit 1 if the committed file is stale

Both modes build first, so neither can pass by reading a stale artifact.
"""

import difflib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "src"
# Enums live in interfaces because that is what consumers import. Building this one
# directory keeps the AST build at ~20ms instead of a full via-IR compile of the tree,
# and the check below is what stops that scope from silently going out of date.
AST_SCOPE = SRC / "interfaces"
AST_OUT = REPO / "out-ast"
TARGET = REPO / "exports" / "enums.json"

HEADER = (
    "Generated by script/tools/gen_enums.py from the Solidity AST. Do not edit. "
    "A member's ordinal is its index in `members`."
)

# Matches a Solidity enum declaration at the start of a line, ignoring indentation.
# Deliberately crude: it is a scope tripwire, not a parser. The AST below is what
# actually produces the output, so a false positive here costs a failed build that a
# human resolves, while a false negative is the failure this whole file exists to
# prevent. Erring toward over-matching is the safe direction.
ENUM_DECL = re.compile(r"^\s*enum\s+\w+\s*\{", re.MULTILINE)


def enum_files() -> list[Path]:
    """Every .sol file under src/ that declares an enum."""
    return sorted(p for p in SRC.rglob("*.sol") if ENUM_DECL.search(p.read_text()))


def assert_scope_still_holds(files: list[Path]) -> None:
    """Fail closed if an enum is declared outside the directory this script compiles.

    The build scope is an optimisation, and an optimisation that quietly narrows what a
    guard can see is worse than no guard: the export would still regenerate, still diff
    clean, and still omit the new enum entirely. So a declaration outside the scope is a
    hard error telling the author to widen AST_SCOPE, never a silent omission.
    """
    stray = [p for p in files if AST_SCOPE not in p.parents]
    if stray:
        rel = "\n  ".join(str(p.relative_to(REPO)) for p in stray)
        sys.exit(
            f"Enum declared outside {AST_SCOPE.relative_to(REPO)}, which this script does "
            f"not compile:\n  {rel}\n"
            "Widen AST_SCOPE in script/tools/gen_enums.py, or move the enum. Refusing to "
            "publish an export that would omit it."
        )


def build_ast() -> None:
    subprocess.run(
        ["forge", "build", str(AST_SCOPE.relative_to(REPO))],
        cwd=REPO,
        env={**os.environ, "FOUNDRY_PROFILE": "ast"},
        check=True,
        stdout=subprocess.DEVNULL,
    )


def walk_enums(node, out: dict) -> None:
    if isinstance(node, dict):
        if node.get("nodeType") == "EnumDefinition":
            out[node["canonicalName"]] = [m["name"] for m in node["members"]]
        for value in node.values():
            walk_enums(value, out)
    elif isinstance(node, list):
        for value in node:
            walk_enums(value, out)


def collect() -> dict:
    found: dict[str, list[str]] = {}
    sources: dict[str, str] = {}
    for artifact in sorted(AST_OUT.rglob("*.json")):
        ast = json.loads(artifact.read_text()).get("ast")
        if not ast:
            continue
        before = set(found)
        walk_enums(ast, found)
        # An artifact's AST includes its imports, so the same enum appears in every
        # artifact that imports it. `absolutePath` of the artifact being read is
        # therefore not the declaring file; the first one to yield a given enum is.
        for name in set(found) - before:
            sources[name] = ast.get("absolutePath", "")
    if not found:
        sys.exit(
            f"No enums found in {AST_OUT.name}. The AST profile did not emit an `ast` key, "
            "so this would have published an empty export that diffs clean forever."
        )
    return {
        "_generated": HEADER,
        "enums": {
            name: {"sourceFile": sources[name], "members": found[name]}
            for name in sorted(found)
        },
    }


def main() -> None:
    check = "--check" in sys.argv[1:]
    assert_scope_still_holds(enum_files())
    build_ast()
    rendered = json.dumps(collect(), indent=2) + "\n"

    if not check:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(rendered)
        print(f"wrote {TARGET.relative_to(REPO)}")
        return

    if not TARGET.exists():
        sys.exit(f"{TARGET.relative_to(REPO)} is missing. Run script/tools/gen_enums.py.")
    if TARGET.read_text() != rendered:
        diff = difflib.unified_diff(
            TARGET.read_text().splitlines(),
            rendered.splitlines(),
            fromfile="committed",
            tofile="regenerated",
            lineterm="",
        )
        print("\n".join(diff))
        sys.exit(
            f"{TARGET.relative_to(REPO)} is stale. Run script/tools/gen_enums.py and "
            "commit the result."
        )
    print(f"{TARGET.relative_to(REPO)} is up to date.")


if __name__ == "__main__":
    main()
